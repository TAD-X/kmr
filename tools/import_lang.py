"""Import the original mod's translations (reference/original/.../lang/*.lang, 1.7.10 format) into
src/main/resources/assets/kitchen/lang/<code>.json, but only for keys that exist in this port's English file
(src/main/generated/assets/kitchen/lang/en_us.json). Keys the port does not have are skipped; missing keys fall
back to English in game. Run: python tools/import_lang.py (needs reference/original/).

English itself is generated by datagen (KitchenLangProvider) and is not touched here.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "reference/original/src/main/resources/assets/kitchen/lang"
EN = ROOT / "src/main/generated/assets/kitchen/lang/en_us.json"
OUT = ROOT / "src/main/resources/assets/kitchen/lang"

# 1.7.10 item ids that were renamed in this port.
ITEM_RENAMES = {
    "bacon_raw": "raw_bacon",
    "bacon_cooked": "bacon",
    "chicken_fillet_raw": "raw_chicken_fillet",
    "chicken_fillet_cooked": "chicken_fillet",
}
BLOCK_RENAMES = {"frying_pan": "pan"}
JAMS = {"peanut": "peanut_jam", "apple": "apple_jam", "strawberry": "strawberry_jam"}


def parse(path):
    entries = {}
    text = path.read_text(encoding="utf-8-sig", errors="replace")
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        entries[key.strip()] = value.strip()
    return entries


def convert(old):
    """Old key and value to (new key, value) pairs in this port's naming."""
    out = {}
    for key, value in old.items():
        m = re.fullmatch(r"tile\.(\w+)\.name", key)
        if m:
            out["block.kitchen." + BLOCK_RENAMES.get(m.group(1), m.group(1))] = value
            continue
        m = re.fullmatch(r"item\.(\w+)\.name", key)
        if m:
            name = ITEM_RENAMES.get(m.group(1), m.group(1))
            out["item.kitchen." + name] = value
            continue
        m = re.fullmatch(r"jam\.(\w+)\.name", key)
        if m and m.group(1) in JAMS:
            jam = JAMS[m.group(1)]
            out["item.kitchen." + jam] = value
            out["layer.kitchen." + jam] = value
            continue
        if key == "item.jam_jar.empty.name":
            out["item.kitchen.jam_jar"] = value
        elif key == "item.sandwichable.sandwichable_msg":
            out["tooltip.kitchen.sandwichable"] = value
        elif key == "item.jam_jar.uses_left_msg":
            out["tooltip.kitchen.servings_left"] = value + ": %s"
        elif key == "itemGroup.tabKitchen":
            out["itemGroup.kitchen.kitchen"] = value
    return out


def main():
    if not SRC.is_dir():
        raise SystemExit(f"Original lang files not found: {SRC} (clone the original into reference/original first)")
    english = json.loads(EN.read_text(encoding="utf-8"))
    OUT.mkdir(parents=True, exist_ok=True)
    written = 0
    for lang_file in sorted(SRC.glob("*.lang")):
        code = lang_file.stem.lower()
        if code == "en_us":
            continue
        converted = convert(parse(lang_file))
        kept = {k: v for k, v in converted.items() if k in english and v}
        if not kept:
            continue
        (OUT / (code + ".json")).write_text(
            json.dumps(dict(sorted(kept.items())), ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        written += 1
        print(f"{code}: {len(kept)} of {len(english)} keys")
    print(f"wrote {written} language files to {OUT}")


if __name__ == "__main__":
    main()
